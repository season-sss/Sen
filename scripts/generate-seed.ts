/**
 * Generates supabase/seed.sql — the server-side question bank for online games.
 * Answers are written only to game_questions.answer (never readable by clients);
 * payload holds what players may see (order-question tokens are pre-shuffled).
 *
 *   npm run db:seed
 */
import { writeFileSync } from 'node:fs';
import { GAMES, generateGameQuestions, type GameId } from '../src/lib/games/games';
import { createRng, shuffle } from '../src/lib/util/random';

const LEVELS = ['A1', 'A2', 'B1', 'B2'] as const;
const PER_GAME_LEVEL = 120;
const esc = (s: string) => s.replace(/'/g, "''");

const rows: string[] = [];
const seen = new Set<string>();
for (const g of GAMES.filter((x) => x.online)) {
  for (const level of LEVELS) {
    let added = 0;
    for (let seed = 1; seed < 400 && added < PER_GAME_LEVEL; seed++) {
      for (const q of generateGameQuestions(g.id as GameId, { maxLevel: level, seed, count: g.rounds })) {
        if (q.kind === 'match') continue;
        const id = `${g.id}:${level}:${q.id}`;
        if (seen.has(id)) continue;
        seen.add(id);
        let payload: Record<string, unknown>;
        let answer: unknown;
        const base = { prompt: q.prompt, promptTh: q.promptTh ?? null, audio: q.audio ?? null, section: q.section, level: q.level };
        if (q.kind === 'mcq') {
          payload = { ...base, kind: 'mcq', options: q.options };
          answer = q.answer;
        } else if (q.kind === 'text') {
          payload = { ...base, kind: 'text', hint: q.hint ?? null };
          answer = q.answers;
        } else {
          const rng = createRng(seed * 7919 + added);
          let tokens = shuffle(q.tokens, rng);
          if (tokens.join(' ') === q.tokens.join(' ') && tokens.length > 1) tokens = [...tokens.slice(1), tokens[0]];
          payload = { ...base, kind: 'order', tokens };
          answer = q.tokens;
        }
        rows.push(`('${esc(id)}','${g.id}','${level}','${q.kind}','${esc(JSON.stringify(payload))}'::jsonb,'${esc(JSON.stringify(answer))}'::jsonb)`);
        added++;
        if (added >= PER_GAME_LEVEL) break;
      }
    }
  }
}

const sql = `-- Generated by scripts/generate-seed.ts — do not edit by hand.
-- ${rows.length} questions for online games.
insert into public.game_questions (id, game_id, level, kind, payload, answer) values
${rows.join(',\n')}
on conflict (id) do update set payload = excluded.payload, answer = excluded.answer;
`;
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql);
console.log(`wrote supabase/seed.sql with ${rows.length} questions`);
